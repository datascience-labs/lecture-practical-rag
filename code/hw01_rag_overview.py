# 실행: python hw01_rag_overview.py [--task 1 2] [--list]

from hw_common import get_client, llm_text, run_tasks, skip

QUESTION = "우리 회사 '판교 오피스'의 회의실 예약 규칙을 알려줘."
CONTEXT = """[사내 규정 3.2조] 판교 오피스 회의실은
그룹웨어에서 최대 2주 전부터 예약 가능하며,
6인 이상 회의실은 부서장 승인이 필요하다."""


def task1(args):
    """컨텍스트 유무 비교 — 같은 질문을 두 방식으로 물어 답변을 나란히 기록한다."""
    client = get_client()
    if client is None:
        skip("ANTHROPIC_API_KEY가 필요한 과제다.")
        return

    print(f"질문: {QUESTION}\n")
    print("--- (1) 컨텍스트 없이 ---")
    without = llm_text(client, "간결하게 답하라.", QUESTION, max_tokens=512)
    print(without)

    print("\n--- (2) 컨텍스트 포함 ---")
    with_ctx = llm_text(
        client, "간결하게 답하라.",
        f"다음 문서를 참고해 답변해줘.\n\n<문서>\n{CONTEXT}\n</문서>\n\n질문: {QUESTION}",
        max_tokens=512)
    print(with_ctx)

    print("""
--- 기록 (관찰 포인트) ---
- (1)은 학습 데이터에 없는 사내 정보라 "알 수 없다"고 답하거나, 그럴듯한
  일반론/추측(환각)을 만들어낸다 — 어느 쪽이 나왔는지 기록하라.
- (2)는 "2주 전부터", "6인 이상은 부서장 승인"처럼 문서의 사실을 정확히 인용한다.
- 이 차이가 RAG의 존재 이유: 모델을 재학습하지 않고 컨텍스트(A)만으로
  최신·사내 정보를 답하게 만든다. 2회차부터 이 컨텍스트를 '검색(R)'으로 자동화한다.""")


def task2(args):
    """RAG 문제 정의 — 17회차 종합 프로젝트의 출발점이 되는 한 장짜리 기획."""
    print("""이 과제는 코드가 아니라 '문제 정의서' 작성이 결과물이다.
아래는 이 강의 실습 데이터(가상 기업 퍼플델타)를 예로 든 작성 예시다.

--- 작성 예시: 퍼플델타 사내 문서 QA 봇 ---
1. 어떤 문서?
   - 임직원 핸드북 (휴가·경비·보안 규정, 8개 장) — 반기마다 개정
   - 회사 문서 12건 (조직도, 제품 스펙, 고객/공급사, 전결 규정)
2. 어떤 질문? (실제 사용자가 할 법한 것)
   - 조회형: "연차 며칠?", "법인카드 증빙 기한은?"          → 1~5회차로 해결
   - 관계형: "김철수 상사가 결재 가능한 최대 금액은?"        → 10~12회차 필요
   - 조망형: "우리 회사 사업 구조를 요약해줘"               → 11~12회차 필요
3. 기대하는 답변 형태?
   - 근거 문서(출처) 표기 필수, 문서에 없으면 "없다"고 답할 것 (환각 금지)
   - 규정 인용은 원문 수치 그대로 (15일을 "약 2주"로 바꾸지 말 것)

--- 본인 도메인용 템플릿 (채워서 제출) ---
1. 문서:    [종류 / 분량 / 갱신 주기 / 접근 권한 제약]
2. 질문:    [유형별 예시 5개 — 나중에 9회차 평가셋의 씨앗이 된다]
3. 답변 형태: [출처 표기? 길이? 거절 조건? 민감정보 처리?]
4. 성공 기준: [무엇이 되면 "쓸 만하다"고 판단할 것인가 — 측정 가능하게]

팁: 3번 질문 예시를 지금 구체적으로 적어둘수록 9회차(평가셋 구축)와
17회차(종합 프로젝트)가 쉬워진다.""")


