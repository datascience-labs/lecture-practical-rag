# 과제 1: 실습 3 코드에서 컨텍스트 유무에 따른 답변 차이를 비교하고 기록  (API 키 필요)
# 과제 2: RAG로 해결하고 싶은 문제 1가지 정의 — 작성 예시(퍼플델타)와 템플릿
